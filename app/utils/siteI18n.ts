export function normalizeSiteLanguage(code: string | undefined | null): SiteLanguage {
  return SITE_LANGUAGES.some(l => l.code === code) ? (code as SiteLanguage) : 'en'
}

export function siteT(lang: SiteLanguage, key: SiteMessageKey, params?: Record<string, string | number>) {
  let text = messages[lang]?.[key] ?? en[key]
  for (const [name, value] of Object.entries(params ?? {})) text = text.replace(`{${name}}`, String(value))
  return text
}

/** Weekday name; 0 = Sunday */
export function siteWeekday(lang: SiteLanguage, day: number) {
  // 7 Jan 2024 was a Sunday
  return new Intl.DateTimeFormat(lang, { weekday: 'long' }).format(new Date(2024, 0, 7 + day))
}

/** "22:00" → "22:00" or "10:00 PM", depending on the language */
export function siteTime(lang: SiteLanguage, time: string) {
  const [h, m] = time.split(':').map(Number)
  if (Number.isNaN(h)) return time
  return new Intl.DateTimeFormat(lang, { hour: 'numeric', minute: '2-digit' }).format(new Date(2024, 0, 1, h, m || 0))
}

export const SITE_LANG_KEY: InjectionKey<Ref<SiteLanguage>> = Symbol('site-language')

/** Translator for components inside a site page (BioPageView provides the language) */
export function useSiteI18n() {
  const lang = inject(SITE_LANG_KEY, ref<SiteLanguage>('en'))
  return {
    lang,
    t: (key: SiteMessageKey, params?: Record<string, string | number>) => siteT(lang.value, key, params),
    weekday: (day: number) => siteWeekday(lang.value, day),
    time: (time: string) => siteTime(lang.value, time),
  }
}
